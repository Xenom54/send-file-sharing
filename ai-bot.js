function reply(mode, prompt, userName) {
  const m = mode === 1 ? 1 : 0;
  const text = String(prompt || '').trim();
  const name = String(userName || 'صاحبي').slice(0, 30);

  let out;
  if (!text) {
    out = pick(EMPTY[m]);
  } else {
    out = null;
    for (const intent of INTENTS) {
      if (intent.test.test(text)) { out = pick(intent[m]); break; }
    }
    if (!out) out = pick(DEFAULT[m]);
  }
  return out
    .replace(/\{name\}/g, name)
    .replace(/\{time\}/g, now());
}

